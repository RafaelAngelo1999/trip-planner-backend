export async function seedFlights(): Promise<FlightEntity[]> {
  console.log('🌱 Seeding flights...');

  const flights: FlightEntity[] = [];

  for (const flightData of flightSeedData) {
    try {
      const flight = FlightEntity.create(flightData);
      flights.push(flight);
    } catch (error) {
      console.error(`Error creating flight ${flightData.flightNumber}:`, error);
    }
  }

  console.log(`✅ Created ${flights.length} flights`);
  return flights;
}
